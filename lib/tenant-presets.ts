// Default data imports for a tenant's own SoftOne → tables in its warehouse schema t_<tenantId>.
// Verified against the installation before creation (same fallbacks as the DGsoft presets).
// History: FULL imports rows from the start of (current fiscal year − 2). INCREMENTAL either
// upserts by UPDDATE or re-imports a rolling window (edits + deletions are reflected).

import type { Columns } from "@/lib/warehouse-writer";

/** Extra sync modes (stored on the job): child rows of documents, or rows per fiscal year. */
export type JobOptions = {
  parent?: { table: string; key: string; filter?: string; dateField: string; updField: string };
  yearField?: string;
  /** yearField mode: FULL imports every fiscal year of the company (not only the BI history). */
  allYears?: boolean;
  chunkField?: string;
  chunkValues?: number[];
};

export type TenantPreset = {
  key: string;
  name: string;
  group: "Λογιστική" | "Παραστατικά" | "Αποθήκη" | "Μητρώα";
  requires: "GL" | "SALES" | "PURCHASES" | "ANY";
  table: string;
  targetTable: string;
  keyField: string;
  columns: Columns;
  /** Fields that may be missing in some installations (dropped on fallback). */
  optional?: string[];
  updField?: string;
  dateField?: string;
  windowDays?: number;
  filter?: string; // {COMPANY} → connection company (dropped if the table has no COMPANY column)
  intervalMinutes: number;
  options?: JobOptions;
  /** Always-false condition used to verify the fields (default 1=0; some tables reject it). */
  probe?: string;
};

