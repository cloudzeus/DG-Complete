import "server-only";

// Builds the single docker-compose file pasted into Coolify (Docker Compose Empty).
// Secrets are referenced as ${VARS} and supplied separately as Coolify environment variables.

export type ComposeTarget = { host: string; port: number; database: string; ssl: boolean };

export type ComposeInput = {
  apiUrl: string;
  devUrl: string | null;
  controlPlaneUrl: string;
  jwtIssuer: string;
  jwtAudience: string;
  warehouse: ComposeTarget;
  dev: ComposeTarget | null;
};

// Embedded as the content of /cube/conf/cube.js. Must not contain "$" (Coolify/compose interpolation).
export const CUBE_JS = `// DGsmart BI — multi-tenant Cube config (generated by the DGsmart BI app).
// JWT payload (signed by the app): { tenantId, modules?: string[] }
// Each tenant → warehouse role r_<tenantId>, search_path = t_<tenantId>, SELECT only.
const crypto = require('crypto');

const isTenantId = (s) => typeof s === 'string' && s.length > 0 && s.length <= 40 && !/[^a-z0-9]/.test(s);

function tenantOf(ctx) {
  const id = ctx && ctx.tenantId;
  if (!isTenantId(id)) throw new Error('Unauthorized: missing or invalid tenantId');
  return id;
}

function rolePassword(id) {
  return crypto.createHmac('sha256', process.env.WH_ROLE_SECRET).update(id).digest('hex');
}

// The data model is versioned in the app's git repo and served by the app (control plane).
// Cached for 60s; on a failed fetch the last good model keeps serving.
let model = { at: 0, data: null };
async function loadModel() {
  if (model.data && Date.now() - model.at < 60000) return model.data;
  try {
    const res = await fetch(process.env.CONTROL_PLANE_URL + '/api/internal/cube/model', {
      headers: { Authorization: 'Bearer ' + process.env.CONTROL_PLANE_TOKEN },
    });
    if (!res.ok) throw new Error('HTTP ' + res.status);
    const data = await res.json();
    if (!model.data || model.data.version !== data.version) {
      console.log('[dgsmart] model version ' + data.version + ': ' + data.files.length + ' files, ' +
        data.files.reduce((n, f) => n + f.content.length, 0) + ' chars');
    }
    model = { at: Date.now(), data: data };
  } catch (err) {
    console.error('model fetch failed:', err.message);
    if (!model.data) throw err;
    model.at = Date.now();
  }
  return model.data;
}

function memberCubes(q) {
  const cubes = new Set();
  const add = (m) => typeof m === 'string' && cubes.add(m.split('.')[0]);
  (q.measures || []).forEach(add);
  (q.dimensions || []).forEach(add);
  (q.segments || []).forEach(add);
  (q.timeDimensions || []).forEach((td) => add(td.dimension));
  const walk = (list) => (list || []).forEach((f) => {
    if (f.or) walk(f.or); else if (f.and) walk(f.and); else add(f.member || f.dimension);
  });
  walk(q.filters);
  return cubes;
}

module.exports = {
  // Compile / meta / error events of Cube itself, regardless of CUBEJS_LOG_LEVEL (diagnostics).
  logger: (msg, params) => {
    if (/ompil|rror|eta|chema|Load/.test(msg)) {
      let p = '';
      try { p = JSON.stringify(params); } catch (e) { p = String(params); }
      console.log('[cube] ' + msg + ' ' + p.slice(0, 1500));
    }
  },
  // A new model version gets its own app id → a fresh compile (hot recompiles of a running app
  // were observed to yield an empty model). The previous version's compiler ages out of the cache.
  contextToAppId: ({ securityContext }) =>
    'CUBE_APP_' + tenantOf(securityContext) + '_' + (model.data ? model.data.version : 'init'),
  contextToOrchestratorId: ({ securityContext }) => 'CUBE_ORCH_' + tenantOf(securityContext),
  schemaVersion: async () => (await loadModel()).version,
  // Each repository (one per compiled app) sees the files with a unique trailing comment, so a
  // compile never reuses anything cached from another compile; every call is logged.
  repositoryFactory: ({ securityContext }) => {
    const nonce = Date.now().toString(36) + Math.random().toString(36).slice(2, 8);
    return {
      dataSchemaFiles: async () => {
        const m = await loadModel();
        console.log('[dgsmart] dataSchemaFiles tenant=' + (securityContext && securityContext.tenantId) +
          ' version=' + m.version + ' files=' + m.files.length + ' nonce=' + nonce);
        return m.files.map((f) => ({
          fileName: f.fileName,
          content: f.content + (f.fileName.endsWith('.js') ? '\\n// ' : '\\n# ') + nonce + '\\n',
        }));
      },
    };
  },

  driverFactory: ({ securityContext }) => {
    const id = tenantOf(securityContext);
    return { type: 'postgres', user: 'r_' + id, password: rolePassword(id), readOnly: true };
  },

  preAggregationsSchema: ({ securityContext }) => 'pre_aggregations_' + tenantOf(securityContext),

  queryRewrite: (query, { securityContext }) => {
    tenantOf(securityContext);
    const allowed = Array.isArray(securityContext.modules) ? new Set(securityContext.modules) : null;
    if (allowed) {
      for (const c of memberCubes(query)) {
        if (!allowed.has(c)) throw new Error("Forbidden: '" + c + "' is not included in your plan");
      }
    }
    return query;
  },

  scheduledRefreshContexts: async () => {
    try {
      const res = await fetch(process.env.CONTROL_PLANE_URL + '/api/internal/cube/tenants', {
        headers: { Authorization: 'Bearer ' + process.env.CONTROL_PLANE_TOKEN },
      });
      if (!res.ok) throw new Error('HTTP ' + res.status);
      const tenants = await res.json();
      return tenants
        .filter((t) => isTenantId(t.tenantId))
        .map((t) => ({ securityContext: { tenantId: t.tenantId, modules: t.modules } }));
    } catch (err) {
      console.error('scheduledRefreshContexts failed:', err.message);
      return [];
    }
  },
};
`;

const indent = (text: string, spaces: number) =>
  text
    .split("\n")
    .map((line) => (line ? " ".repeat(spaces) + line : line))
    .join("\n");

/** Quotes a value for a compose `- KEY=value` list item when it needs it. */
const v = (value: string | number | boolean) => {
  const s = String(value);
  if (s.includes("$")) throw new Error(`Value must not contain '$': ${s}`);
  return s;
};

function warehouseEnv(w: ComposeTarget) {
  return [
    "CUBEJS_DB_TYPE=postgres",
    `CUBEJS_DB_HOST=${v(w.host)}`,
    `CUBEJS_DB_PORT=${v(w.port)}`,
    `CUBEJS_DB_NAME=${v(w.database)}`,
    `CUBEJS_DB_SSL=${v(w.ssl)}`,
  ];
}

function envList(items: string[]) {
  return items.map((i) => `      - ${i}`).join("\n");
}

const CUBESTORE_WORKERS = "cubestore_worker_1:10001,cubestore_worker_2:10002";

function cubestoreWorker(n: number) {
  const name = `cubestore_worker_${n}`;
  const port = 10000 + n;
  return `  ${name}:
    image: cubejs/cubestore:latest
    restart: unless-stopped
    depends_on:
      - cubestore_router
    environment:
${envList([
  `CUBESTORE_SERVER_NAME=${name}:${port}`,
  `CUBESTORE_WORKER_PORT=${port}`,
  "CUBESTORE_META_ADDR=cubestore_router:9999",
  `CUBESTORE_WORKERS=${CUBESTORE_WORKERS}`,
  "CUBESTORE_REMOTE_DIR=/cube/data",
  "CUBESTORE_TELEMETRY=false",
])}
    volumes:
      - cubestore_data:/cube/data`;
}

export function buildCubeCompose(input: ComposeInput): string {
  const sharedProdEnv = [
    "CUBEJS_DEV_MODE=false",
    "CUBEJS_TELEMETRY=false",
    "CUBEJS_LOG_LEVEL=warn",
    "CUBEJS_API_SECRET=${CUBEJS_API_SECRET}",
    "CUBEJS_JWT_ALGS=HS256",
    `CUBEJS_JWT_ISSUER=${v(input.jwtIssuer)}`,
    `CUBEJS_JWT_AUDIENCE=${v(input.jwtAudience)}`,
    ...warehouseEnv(input.warehouse),
    "CUBEJS_DB_MAX_POOL=4",
    "WH_ROLE_SECRET=${WH_ROLE_SECRET}",
    `CONTROL_PLANE_URL=${v(input.controlPlaneUrl.replace(/\/+$/, ""))}`,
    "CONTROL_PLANE_TOKEN=${CONTROL_PLANE_TOKEN}",
    "CUBEJS_CUBESTORE_HOST=cubestore_router",
    "CUBEJS_CUBESTORE_PORT=3030",
    "CUBEJS_CACHE_AND_QUEUE_DRIVER=cubestore",
    "CUBEJS_EXTERNAL_DEFAULT=true",
    "CUBEJS_SCHEDULED_REFRESH_DEFAULT=true",
    // The native (Rust) YAML transpiler silently dropped every cube of our model; use the JS one.
    "CUBEJS_TRANSPILATION_NATIVE=false",
  ];

  const header = `# DGsmart BI — Cube.dev stack για Coolify (παράχθηκε από την εφαρμογή DGsmart BI)
# Coolify → New Resource → Docker Compose Empty → επικόλληση.
# Domains: ορίζονται ΜΟΝΟ από το Coolify UI (χωρίς SERVICE_FQDN → κανένα αυτόματο domain):
#   cube      → ${input.apiUrl}  (internal port 4000)${input.dev && input.devUrl ? `\n#   cube_dev  → ${input.devUrl}  (internal port 4000)` : ""}
# Environment variables: επικόλληση του .env που δίνει η εφαρμογή (Developer view).
# Warehouse: ${input.warehouse.host}:${input.warehouse.port}/${input.warehouse.database}${
    input.dev ? `\n# Dev:       ${input.dev.host}:${input.dev.port}/${input.dev.database}` : ""
  }
`;

  const cube = `  cube:
    image: cubejs/cube:latest
    restart: unless-stopped
    depends_on:
      - cubestore_router
    environment:
${envList([...sharedProdEnv, "CUBEJS_REFRESH_WORKER=false"])}
    volumes:
      - type: bind
        source: ./cube.js
        target: /cube/conf/cube.js
        content: |
${indent(CUBE_JS.trimEnd(), 10)}
    healthcheck:
      test: ["CMD", "node", "-e", "fetch('http://127.0.0.1:4000/readyz').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"]
      interval: 15s
      timeout: 5s
      retries: 10
      start_period: 30s`;

  const refresh = `  cube_refresh:
    image: cubejs/cube:latest
    restart: unless-stopped
    depends_on:
      - cube
      - cubestore_router
    environment:
${envList([...sharedProdEnv, "CUBEJS_REFRESH_WORKER=true"])}
    volumes:
      - type: bind
        source: ./cube.js
        target: /cube/conf/cube.js`;

  const dev = input.dev
    ? `  cube_dev:
    image: cubejs/cube:latest
    restart: unless-stopped
    environment:
${envList([
  "CUBEJS_DEV_MODE=true",
  "CUBEJS_TELEMETRY=false",
  "CUBEJS_PLAYGROUND_AUTH_SECRET=${CUBEJS_PLAYGROUND_AUTH_SECRET}",
  "CUBEJS_API_SECRET=${CUBEJS_DEV_API_SECRET}",
  ...warehouseEnv(input.dev),
  "CUBEJS_DB_USER=${DEV_DB_USER}",
  "CUBEJS_DB_PASS=${DEV_DB_PASS}",
])}
    volumes:
      - cube_model:/cube/conf/model`
    : null;

  const router = `  cubestore_router:
    image: cubejs/cubestore:latest
    restart: unless-stopped
    environment:
${envList([
  "CUBESTORE_SERVER_NAME=cubestore_router:9999",
  "CUBESTORE_META_PORT=9999",
  `CUBESTORE_WORKERS=${CUBESTORE_WORKERS}`,
  "CUBESTORE_REMOTE_DIR=/cube/data",
  "CUBESTORE_TELEMETRY=false",
])}
    volumes:
      - cubestore_data:/cube/data`;

  const services = [cube, refresh, dev, router, cubestoreWorker(1), cubestoreWorker(2)].filter(Boolean).join("\n\n");

  return `${header}
services:
${services}

volumes:
  cube_model:
  cubestore_data:
`;
}

/** The environment variables to paste into Coolify (contains secrets). */
export function buildCubeEnv(env: {
  apiSecret: string;
  roleSecret: string;
  internalToken: string;
  playgroundSecret: string;
  devApiSecret: string;
  devUser?: string;
  devPassword?: string;
}) {
  const lines = [
    `CUBEJS_API_SECRET=${env.apiSecret}`,
    `WH_ROLE_SECRET=${env.roleSecret}`,
    `CONTROL_PLANE_TOKEN=${env.internalToken}`,
  ];
  if (env.devUser !== undefined) {
    lines.push(
      `CUBEJS_PLAYGROUND_AUTH_SECRET=${env.playgroundSecret}`,
      `CUBEJS_DEV_API_SECRET=${env.devApiSecret}`,
      `DEV_DB_USER=${env.devUser}`,
      `DEV_DB_PASS=${env.devPassword ?? ""}`,
    );
  }
  return lines.join("\n") + "\n";
}
